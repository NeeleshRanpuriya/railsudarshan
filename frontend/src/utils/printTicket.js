function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

export function printTicket(ticket) {
  const passengers = (ticket.passengers || []).map((passenger) => `
    <tr>
      <td>${escapeHtml(passenger.name)}</td>
      <td>${escapeHtml(passenger.age)}</td>
      <td>${escapeHtml(passenger.gender)}</td>
      <td>${escapeHtml(passenger.coach || ticket.coach)}-${escapeHtml(passenger.berthNumber)} (${escapeHtml(passenger.berthType)})</td>
    </tr>
  `).join('');

  const printFrame = document.createElement('iframe');
  printFrame.setAttribute('title', 'Printable RailRaksha ticket');
  printFrame.style.position = 'fixed';
  printFrame.style.right = '0';
  printFrame.style.bottom = '0';
  printFrame.style.width = '0';
  printFrame.style.height = '0';
  printFrame.style.border = '0';
  printFrame.style.visibility = 'hidden';
  document.body.appendChild(printFrame);

  const printDocument = printFrame.contentDocument;
  const printWindow = printFrame.contentWindow;

  if (!printDocument || !printWindow) {
    printFrame.remove();
    alert('Unable to prepare the ticket for printing. Please try again.');
    return;
  }

  printDocument.open();
  printDocument.write(`
    <!doctype html>
    <html>
      <head>
        <title>RailRaksha Ticket - ${escapeHtml(ticket.pnr || ticket.id)}</title>
        <style>
          body { font-family: Arial, sans-serif; color: #0f172a; margin: 32px; }
          .header { display: flex; justify-content: space-between; border-bottom: 3px solid #047857; padding-bottom: 16px; }
          h1 { margin: 0; color: #064e3b; font-size: 24px; }
          .muted { color: #475569; font-size: 13px; }
          .status { color: #047857; font-weight: 700; }
          .summary { display: grid; grid-template-columns: repeat(3, 1fr); gap: 16px; margin: 24px 0; }
          .field { border: 1px solid #cbd5e1; border-radius: 8px; padding: 10px; }
          .label { color: #64748b; font-size: 11px; text-transform: uppercase; }
          .value { font-weight: 700; margin-top: 5px; }
          table { border-collapse: collapse; width: 100%; margin-top: 12px; }
          th, td { border: 1px solid #cbd5e1; padding: 10px; text-align: left; font-size: 13px; }
          th { background: #ecfdf5; }
          .footer { margin-top: 28px; border-top: 1px solid #cbd5e1; padding-top: 12px; }
          @media print { body { margin: 16px; } }
        </style>
      </head>
      <body>
        <div class="header">
          <div>
            <h1>RailRaksha</h1>
            <div class="muted">Smart Booking &amp; Passenger Safety Ecosystem</div>
          </div>
          <div class="status">CONFIRMED</div>
        </div>
        <div class="summary">
          <div class="field"><div class="label">PNR</div><div class="value">${escapeHtml(ticket.pnr || ticket.id)}</div></div>
          <div class="field"><div class="label">Train</div><div class="value">${escapeHtml(ticket.trainNumber)} — ${escapeHtml(ticket.trainName)}</div></div>
          <div class="field"><div class="label">Journey Date</div><div class="value">${escapeHtml(ticket.journeyDate)}</div></div>
          <div class="field"><div class="label">From</div><div class="value">${escapeHtml(ticket.from)}</div></div>
          <div class="field"><div class="label">To</div><div class="value">${escapeHtml(ticket.to)}</div></div>
          <div class="field"><div class="label">Class / Fare</div><div class="value">${escapeHtml(ticket.travelClass)} / ₹${escapeHtml(ticket.totalFare)}</div></div>
        </div>
        <h2>Passenger Details</h2>
        <table>
          <thead><tr><th>Name</th><th>Age</th><th>Gender</th><th>Coach / Berth</th></tr></thead>
          <tbody>${passengers || '<tr><td colspan="4">Passenger details unavailable</td></tr>'}</tbody>
        </table>
        <div class="footer muted">Generated by RailRaksha. Please carry a valid government ID during your journey.</div>
      </body>
    </html>
  `);
  printDocument.close();

  const cleanup = () => {
    printWindow.removeEventListener('afterprint', cleanup);
    printFrame.remove();
  };

  printWindow.addEventListener('afterprint', cleanup);
  printWindow.setTimeout(() => {
    printWindow.focus();
    printWindow.print();
    printWindow.setTimeout(cleanup, 1000);
  }, 100);
}
